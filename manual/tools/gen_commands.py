#!/usr/bin/env python3
"""Generate gen/commands.typ from the command registry in
Commands/CommandManager.c (command_populate_all)."""
import re, pathlib
root = pathlib.Path(__file__).resolve().parents[2]
src = (root / "server/Source/Server/Commands/CommandManager.c").read_text()
body = src[src.index("command_manager_t commands[] = {"):src.index("for (unsigned long i = 0")]
who = {0: "everyone", 31: "any logged-in role", 30: "guard or higher", 24: "admin or higher", 16: "manager only"}
rows = []
for m in re.finditer(r'\{"(/\w+)",\s*(\d),\s*&\w+,\s*(\d+),\s*"((?:[^"\\]|\\.)*)"\}', body):
    cmd, parse, perm, desc = m.group(1), m.group(2), int(m.group(3)), m.group(4)
    rows.append((cmd, who.get(perm, f"mask {perm}"), desc))
def typ(s):
    s = s.replace("\\", "\\\\")
    for ch in "#$@*_`<>[]~":
        s = s.replace(ch, "\\" + ch)
    return s
o = ["// generated by tools/gen_commands.py: do not edit", '#import "/template.typ": *', "#cmd-table(("]
for cmd, w, d in sorted(rows):
    o.append(f"  (raw(\"{cmd}\"), [{w}], [{typ(d)}]),")
o.append("))")
(root / "manual/gen/commands.typ").write_text("\n".join(o))
print(len(rows), "commands")
