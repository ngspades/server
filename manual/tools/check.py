#!/usr/bin/env python3
"""make check: (1) every name in api-surface.txt has an entry in the Typst
sources, (2) every ```lua example is valid Lua (luac -p), (3) the built site's
internal links resolve, (4) no placeholder text. Also writes gen/coverage.typ
(counts for the appendix). Exit 1 on any failure."""
import re, sys, pathlib, subprocess, tempfile, os, html.parser

root = pathlib.Path(__file__).resolve().parents[1]
sources = {p: p.read_text() for p in list((root / "chapters").glob("*.typ"))}
alltext = "\n".join(sources.values())
fail = 0

# 1. coverage
surface = [l.split("\t") for l in (root / "api-surface.txt").read_text().splitlines() if l.strip()]
missing = [n for k, n in surface if f'"{n}"' not in alltext]
verified = set(re.findall(r'"([^"]+)"', (root / "gen/verified.typ").read_text()))
if missing:
    fail = 1
    print(f"FAIL coverage: {len(missing)} names of api-surface.txt have no entry:")
    for n in missing:
        print("   ", n)
else:
    print(f"ok   coverage: all {len(surface)} names of api-surface.txt are in the reference")

kinds = {}
for k, n in surface:
    kinds.setdefault(k, []).append(n)
entries = re.findall(r'#entry\("([^"]+)"', alltext)
rows = ["// generated by tools/check.py: do not edit", '#import "/template.typ": *',
        "#wide-table((auto, auto, 1fr), table.header([*Group*], [*Names*], [*Examples*]),"]
labels = {"function": "game.* functions", "method": "player methods", "field": "player fields", "event": "events",
          "mode-field": "game mode fields", "goal-key": "bot goal keys", "intent": "bot intents", "role": "bot roles",
          "sky-field": "game.sky fields", "set-sky-key": "game.set_sky keys", "info-field": "game.server_info fields",
          "class-field": "class table fields", "http-key": "game.http keys", "config": "config keys", "env": "environment variables",
          "evt": "EVT plugin actions"}
for k, names in kinds.items():
    ents = sum(1 for n in names if n in entries)
    rows.append(f'  "{labels.get(k, k)}", "{len(names)}", "{ents} full entries, the rest in tables",')
rows.append(f'  "total", "{len(surface)}", "{len(entries)} entries",')
rows.append(")")
vlist = sorted(n for k, n in surface if n in verified)
unv = sorted(n for k, n in surface if k in ("function", "method", "event") and n not in verified)
rows.append(f"\nVerified by running on a real server: {len(vlist)} of the {len(kinds.get('function', [])) + len(kinds.get('method', [])) + len(kinds.get('event', []))} functions, methods and events.")
rows.append("\nTaken from the C code only (not exercised by the test): " + ", ".join(f"#raw(\"{n}\")" for n in unv) + ".")
(root / "gen/coverage.typ").write_text("\n".join(rows) + "\n")

if "--gen" in sys.argv:
    sys.exit(0)

# 2. lua examples
luac = "luac"
bad = 0
count = 0
for p, text in sources.items():
    for m in re.finditer(r"```lua\n(.*?)```", text, re.S):
        count += 1
        with tempfile.NamedTemporaryFile("w", suffix=".lua", delete=False) as f:
            f.write(m.group(1))
        r = subprocess.run([luac, "-p", f.name], capture_output=True, text=True)
        os.unlink(f.name)
        if r.returncode:
            bad += 1
            print(f"FAIL lua in {p.name}: {r.stderr.strip()}\n{m.group(1)[:200]}")
if bad:
    fail = 1
else:
    print(f"ok   lua: {count} examples parse (luac -p)")

# 3. links in the built site
site = root / "site"
if site.exists() and list(site.glob("*.html")):
    class L(html.parser.HTMLParser):
        def __init__(s):
            super().__init__(); s.links = []; s.ids = set()
        def handle_starttag(s, tag, attrs):
            a = dict(attrs)
            if "id" in a: s.ids.add(a["id"])
            if tag == "a" and a.get("href"): s.links.append(a["href"])
    pages = {}
    for h in site.glob("*.html"):
        p = L(); p.feed(h.read_text()); pages[h.name] = p
    broken = 0
    for name, p in pages.items():
        for href in p.links:
            if href.startswith(("http:", "https:", "mailto:")):
                continue
            target, _, frag = href.partition("#")
            target = target or name
            if target.endswith(".html") and target not in pages:
                broken += 1; print(f"FAIL link {name} -> {href}")
            elif target.endswith(".pdf") and not (site / target).exists():
                broken += 1; print(f"FAIL link {name} -> {href} (no such file)")
            elif frag and target in pages and frag not in pages[target].ids:
                broken += 1; print(f"FAIL anchor {name} -> {href}")
    if broken: fail = 1
    else: print(f"ok   links: {sum(len(p.links) for p in pages.values())} links in {len(pages)} pages resolve")
else:
    print("skip links: site/ not built")

# 4. leftovers
for p, text in sources.items():
    for w in ("TODO", "FIXME", "lorem", "stub"):
        if re.search(rf"\b{w}\b", text):
            fail = 1; print(f"FAIL placeholder '{w}' in {p.name}")
sys.exit(fail)
