#!/usr/bin/env python3
"""Run tests/apitest.lua on a real server and write gen/verified.typ: the
names whose calls ran and answered as the reference says. Needs a built
server (SERVER=<binary>, default server/build/ngspades-server) and python3."""
import os, re, subprocess, sys, threading, http.server, time, pathlib, shutil, socket

root = pathlib.Path(__file__).resolve().parents[2]
man = root / "manual"
binary = pathlib.Path(os.environ.get("SERVER", root / "server/build/ngspades-server"))
log = man / "tests/api-test.log"

class H(http.server.BaseHTTPRequestHandler):
    def do_POST(self):
        n = int(self.headers.get("content-length", 0))
        body = self.rfile.read(n)
        self.send_response(200); self.end_headers(); self.wfile.write(b"echo:" + body)
    def log_message(self, *a): pass

httpd = http.server.HTTPServer(("127.0.0.1", 18765), H)
threading.Thread(target=httpd.serve_forever, daemon=True).start()

cfg = (root / "server/Resources/config.toml").read_text()
cfg = cfg.replace('load = ["server_tools"]', 'load = ["apitest"]\n\n[plugins.apitest]\nallow_hosts = ["127.0.0.1"]\nlabel = "hi"')
cfgpath = man / "tests/test-config.toml"
cfgpath.write_text(cfg)
work = pathlib.Path(os.environ.get("TESTDIR", "/tmp/api-test-root"))
shutil.rmtree(work, ignore_errors=True)
shutil.copytree(root / "server/Resources", work / "Resources", ignore=shutil.ignore_patterns("plugins"))
(work / "Resources/plugins").mkdir()
shutil.copy(cfgpath, work / "Resources/config.toml")
rcon_replies = []

def rcon(lines, delay):
    time.sleep(delay)
    try:
        c = socket.create_connection(("127.0.0.1", 32990), timeout=8)
        c.sendall(("auth " + "x" * 20 + "\n").encode())
        c.recv(64)
        for ln in lines:
            c.sendall((ln + "\n").encode())
            data = b""
            while not data.endswith(b"\x04\n"):
                ch = c.recv(65536)
                if not ch:
                    break
                data += ch
            rcon_replies.append(f"RCON {ln!r} -> {data[:200]!r}")
        c.close()
    except Exception as e:
        print("rcon:", e)

def run(label, extra_args, extra_env, rcon_lines=None, seconds=14):
    env = dict(os.environ, SP_PLUGINS_DIR=str(man / "tests"), SP_MASTER="0", SP_EVENTLOG="1", SP_BOTS_PLAY="1",
               SP_MAP_DOWNLOAD="0", SP_RAND_SEED="1", SP_RCON_PASSWORD="x" * 20,
               SP_RCON_PORT="32990", **extra_env)
    if rcon_lines:
        threading.Thread(target=rcon, args=(rcon_lines, 8), daemon=True).start()
    proc = subprocess.Popen([str(binary), "--root", str(work), "--bots", "6"] + extra_args,
                            env=env, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True,
                            stdin=subprocess.DEVNULL)
    # the game's clock runs in real time here (no SP_FAST): stop it after a while, politely
    threading.Timer(seconds, proc.terminate).start()
    output, _ = proc.communicate(timeout=seconds + 60)
    t = re.sub(r"\x1b\[[0-9;]*m", "", output)
    return f"===== run {label}\n" + t

texts = [
    run("apitest", ["--map", "Busan_Port"], {"SP_PLUGINS": "apitest", "SP_PLUGIN_COMMANDS": "hello"}, ["hello a b", "status"]),
    run("modetest", ["--map", "Busan_Port", "--gamemode", "modetest"], {"SP_PLUGINS": ""}),
    run("pendtest", ["--map", "Busan_Port"], {"SP_PLUGINS": "pendtest", "SP_PLUGIN_ALLOW_MAP": "1", "SP_PLUGIN_COMMANDS": "say"}, seconds=12),
]
text = "\n".join(texts) + "\n" + "\n".join(rcon_replies) + "\n"
log.write_text(text)
ok, bad = {}, {}
for m in re.finditer(r"VERIFY (\S+) (ok|fail) ?(.*)", text):
    (ok if m.group(2) == "ok" else bad)[m.group(1)] = m.group(3)
names = sorted(n for n in ok if "(" not in n and n != "p.fields" and n != "http.on_done")
for n in ("game.time_left", "game.set_time_limit"):
    if n + "(mode)" in ok or n + "(mode, set)" in ok:
        names.append(n)
# names with a parenthesised variant count when the plain call worked or the variant is the real behaviour
extra = {"game.set_mode", "game.set_map", "game.next_map", "game.run_command", "game.objective"}
for n in extra:
    if n + "(denied)" in ok:
        names.append(n)
if "p:kick(bot)" in ok or "p:kick(bot)" in bad:
    names.append("p:kick")
if "game.http" in ok:
    names.append("game.http")
if "game.ban(bot)" in ok or "game.ban(bot)" in bad:
    names.append("game.ban")
if "game.supported_profiles(late)" in bad:
    names.append("game.supported_profiles")
names = sorted(set(names))
if "game.run_command" in ok and "game.run_command" not in names:
    names.append("game.run_command")
names = sorted(set(names))
(man / "gen/verified.typ").write_text("// generated by tools/run_api_test.py: do not edit\n#let verified = (\n" +
                                      "".join(f'  "{n}",\n' for n in names) + ")\n")
print(f"{len(ok)} ok, {len(bad)} fail; {len(names)} verified names")
for k, v in sorted(bad.items()):
    print("FAIL", k, v)
